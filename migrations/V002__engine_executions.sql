/* pgmigrate-encoding: utf-8 */

CREATE SCHEMA engine;

CREATE TABLE engine.executions (
  execution_id uuid PRIMARY KEY,
  draft_id uuid UNIQUE NOT NULL,
  draft_version int NOT NULL CHECK (draft_version > 0),
  actor_id text NOT NULL CHECK (length(trim(actor_id)) > 0),
  command_name text NOT NULL CHECK (length(trim(command_name)) > 0),
  command_version int NOT NULL CHECK (command_version > 0),
  request_hash text NOT NULL CHECK (request_hash ~ '^[0-9a-f]{64}$'),
  request jsonb NOT NULL CHECK (jsonb_typeof(request) = 'object'),
  result jsonb NOT NULL CHECK (jsonb_typeof(result) = 'object'),
  created_at timestamptz NOT NULL DEFAULT now(),
  UNIQUE (execution_id, actor_id)
);

CREATE TABLE engine.idempotency_records (
  actor_id text NOT NULL,
  key text NOT NULL CHECK (length(trim(key)) > 0),
  execution_id uuid NOT NULL,
  created_at timestamptz NOT NULL DEFAULT now(),
  PRIMARY KEY (actor_id, key),
  FOREIGN KEY (execution_id, actor_id) REFERENCES engine.executions (execution_id, actor_id)
);

CREATE TABLE engine.audit_events (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  execution_id uuid UNIQUE NOT NULL REFERENCES engine.executions (execution_id),
  action text NOT NULL CHECK (length(trim(action)) > 0),
  created_at timestamptz NOT NULL DEFAULT now()
);
