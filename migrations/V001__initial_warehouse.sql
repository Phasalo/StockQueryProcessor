DO $$
BEGIN
  -- pgmigrate creates its metadata before executing the first migration.
  IF EXISTS (
    SELECT 1 FROM pg_class
    WHERE relnamespace = current_schema()::regnamespace
      AND relkind IN ('r', 'p', 'v', 'm', 'S', 'f')
      AND relname <> 'schema_version'
  ) OR EXISTS (
    SELECT 1 FROM pg_type
    WHERE typnamespace = current_schema()::regnamespace
      AND typname NOT IN (
        'schema_version', '_schema_version',
        'schema_version_type', '_schema_version_type'
      )
  ) THEN
    RAISE EXCEPTION 'Initial warehouse migration requires an empty schema: %', current_schema();
  END IF;
END $$;

CREATE TYPE "enum_transaction_type" AS ENUM (
  'CONSUMPTION',
  'ISSUE',
  'ADJUSTMENT',
  'PLANNED_RECEIPT',
  'RECEIPT'
);

CREATE TABLE "film_types" (
  "id" INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  "code" varchar(50) UNIQUE NOT NULL,
  "name" varchar(255) NOT NULL
);

CREATE TABLE "materials" (
  "id" INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  "film_type_id" int NOT NULL,
  "brand" varchar(255) NOT NULL,
  "format" int NOT NULL,
  "thickness" int NOT NULL,
  CONSTRAINT "chk_materials_positive_format" CHECK (format > 0),
  CONSTRAINT "chk_materials_positive_thickness" CHECK (thickness > 0)
);

CREATE TABLE "customers" (
  "id" INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  "name" varchar(255) NOT NULL,
  "prod_card_number" varchar(50) NOT NULL
);

CREATE TABLE "suppliers" (
  "id" INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  "name" varchar(255) UNIQUE NOT NULL
);

CREATE TABLE "transactions" (
  "id" INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  "created_at" timestamptz NOT NULL DEFAULT (now()),
  "transaction_type" enum_transaction_type NOT NULL,
  "material_id" int NOT NULL,
  "quantity_delta_kg" decimal(10,2) NOT NULL,
  CONSTRAINT "chk_transactions_nonzero_delta" CHECK (quantity_delta_kg <> 0),
  CONSTRAINT "chk_transactions_delta_sign" CHECK ((transaction_type IN ('CONSUMPTION', 'ISSUE') AND quantity_delta_kg < 0) OR (transaction_type IN ('PLANNED_RECEIPT', 'RECEIPT') AND quantity_delta_kg > 0) OR transaction_type = 'ADJUSTMENT')
);

CREATE TABLE "consumption" (
  "id" INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  "transaction_id" int UNIQUE NOT NULL,
  "customer_id" int NOT NULL
);

CREATE TABLE "issues" (
  "id" INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  "transaction_id" int UNIQUE NOT NULL,
  "customer_id" int NOT NULL,
  "planned_consumption_id" int UNIQUE,
  "actual_date" date
);

CREATE TABLE "planned_receipts" (
  "id" INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  "transaction_id" int UNIQUE NOT NULL,
  "supplier_id" int NOT NULL,
  "order_date" date NOT NULL,
  "planned_date" date NOT NULL
);

CREATE TABLE "receipts" (
  "id" INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  "transaction_id" int UNIQUE NOT NULL,
  "supplier_id" int NOT NULL,
  "planned_receipt_id" int UNIQUE,
  "actual_date" date NOT NULL
);

CREATE TABLE "plan_cancellations" (
  "id" INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  "plan_transaction_id" int NOT NULL,
  "quantity_kg" decimal(10,2) NOT NULL,
  "reason" text NOT NULL,
  "created_at" timestamptz NOT NULL DEFAULT (now()),
  CONSTRAINT "chk_plan_cancellations_positive_quantity" CHECK (quantity_kg > 0),
  CONSTRAINT "chk_plan_cancellations_reason" CHECK (length(trim(reason)) > 0)
);

CREATE UNIQUE INDEX "idx_materials_unique_params" ON "materials" ("film_type_id", "brand", "format", "thickness");

CREATE UNIQUE INDEX ON "customers" ("name", "prod_card_number");

CREATE INDEX "idx_transactions_material_type" ON "transactions" ("material_id", "transaction_type");

CREATE INDEX "idx_plan_cancellations_plan" ON "plan_cancellations" ("plan_transaction_id");

